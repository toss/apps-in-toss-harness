/**
 * Shape of the relay endpoint signature carried in the `sig` query parameter,
 * the session certificates the relay publishes, and the byte strings that get
 * signed.
 *
 * A page opened from a QR test host carries `relay=wss://<tunnel>` and an `at`
 * code, but holds no secret, so the page alone cannot tell whether the tunnel
 * belongs to the developer who built the bundle. The bundle therefore carries
 * one or more root public keys and the device verifies the relay against them
 * before it trusts anything from it.
 *
 * Two keys are involved:
 *
 *   - root key: long-lived, the only key the bundle pins (`relayPublicKeys`,
 *     printed by `debugger relay-key`). It signs nothing but session
 *     certificates.
 *   - session key: short-lived, generated by the daemon in memory. The root key
 *     certifies it for a bounded time window, and it signs each attach link.
 *
 * `sig` value (kept short so the QR stays sparse):
 *
 *   <keyId>.<linkSig>
 *
 *   - keyId: {@link relaySessionKeyId} of the session key (8 chars); it only
 *     picks the certificate, the full key is what verifies
 *   - linkSig: session signature over {@link relayLinkMessage} (86 chars)
 *
 * Certificates: the relay answers `GET {@link RELAY_CERT_PATH}` (no code, no
 * credentials) with {@link RelayCertDocument}, the session certificates that
 * are still valid (current and earlier ones until they expire, so a rotation
 * between QR render and scan still verifies). Each certificate is the root
 * signature over {@link relayCertMessage}. The document is public data.
 *
 *   - algorithm: ECDSA over P-256 with SHA-256 (WebCrypto; Ed25519 is missing
 *     from older Android WebViews)
 *   - signatures: raw `r || s`, 64 bytes, base64url without padding (86 chars)
 *   - public keys: uncompressed point, 65 bytes (`0x04 || X || Y`), base64url
 *     without padding (87 chars)
 *
 * The device checks its clock against [notBefore, notAfter] and refuses a
 * certificate whose window is longer than {@link RELAY_CERT_MAX_LIFETIME_SECONDS}.
 * Earlier formats (`ait-relay-sig-v1`, and a `sig` carrying the certificate
 * itself) are not accepted.
 *
 * Dependency-free (no Node, no DOM, no `URL`) so the browser bundle and the
 * daemon can both import it.
 *
 * SECRET-HANDLING: only public values pass through here. Signatures, public
 * keys and certificates are not secrets; the `at` code is, and this module sees
 * it only as an argument and never logs it.
 */

/** Query parameter that carries the signature. */
export const RELAY_SIGNATURE_PARAM = 'sig';

/** Domain-separation label that starts the link message (signed by the session key). */
export const RELAY_LINK_DOMAIN = 'ait-relay-sig-v2';

/**
 * Domain-separation label that starts the host-name message (signed by the same
 * session key as the link message).
 */
export const RELAY_HOST_DOMAIN = 'ait-relay-host-v1';

/** Query parameter that carries the developer computer's name (optional). */
export const RELAY_HOST_PARAM = 'ahn';

/** Query parameter that carries the signature of the name (optional). */
export const RELAY_HOST_SIGNATURE_PARAM = 'ahs';

/** Longest developer computer name carried in a link. */
export const RELAY_HOST_NAME_MAX_CHARS = 40;

/** Domain-separation label that starts the certificate message (signed by the root key). */
export const RELAY_CERT_DOMAIN = 'ait-relay-cert-v1';

/** Longest certificate window (notAfter - notBefore) the device accepts, in seconds. */
export const RELAY_CERT_MAX_LIFETIME_SECONDS = 3600;

/** Length of a raw `r || s` P-256 signature. */
export const RELAY_SIGNATURE_BYTES = 64;

/** Length of an uncompressed P-256 public point. */
export const RELAY_PUBLIC_KEY_BYTES = 65;

/** base64url (no padding) length of {@link RELAY_SIGNATURE_BYTES} bytes. */
const SIGNATURE_CHARS = 86;

/** base64url (no padding) length of {@link RELAY_PUBLIC_KEY_BYTES} bytes. */
const PUBLIC_KEY_CHARS = 87;

const PUBLIC_KEY_RE = new RegExp(`^[A-Za-z0-9_-]{${PUBLIC_KEY_CHARS}}$`);

/** Path the relay serves the certificate document at (unauthenticated, GET). */
export const RELAY_CERT_PATH = '/relay-cert';

/** `v` of {@link RelayCertDocument}. */
export const RELAY_CERT_DOCUMENT_VERSION = 1;

/** Largest certificate document the device reads, in bytes. */
export const RELAY_CERT_DOCUMENT_MAX_BYTES = 4096;

/** Most certificates one document may list. */
export const RELAY_CERT_DOCUMENT_MAX_CERTS = 4;

/** Length of {@link relaySessionKeyId}. */
export const RELAY_SESSION_KEY_ID_CHARS = 8;

/** Largest unix-seconds value accepted (10 digits). */
const MAX_SECONDS = 9_999_999_999;

const LINK_SIG_RE = new RegExp(
  `^([A-Za-z0-9_-]{${RELAY_SESSION_KEY_ID_CHARS}})\\.([A-Za-z0-9_-]{${SIGNATURE_CHARS}})$`,
);

/**
 * Short id of a session key, used only to pick its certificate: characters
 * 1 to 8 of the encoded key (character 0 is always `B`, from the `0x04`
 * prefix), i.e. 46 bits of the X coordinate. Two keys sharing an id only means
 * the device tries both; the full key is what verifies.
 */
export function relaySessionKeyId(sessionPublicKey: string): string {
  return sessionPublicKey.slice(1, 1 + RELAY_SESSION_KEY_ID_CHARS);
}

/** A parsed `sig` value. Shape is checked; nothing is verified. */
export interface RelayLinkSignature {
  readonly keyId: string;
  readonly linkSignatureBytes: Uint8Array;
}

/**
 * Parses a `sig` value (`<keyId>.<linkSig>`), or returns `null` when it is
 * malformed: wrong field count, length or alphabet, or non-canonical base64url.
 */
export function parseRelaySignature(value: unknown): RelayLinkSignature | null {
  if (typeof value !== 'string') return null;
  const match = LINK_SIG_RE.exec(value);
  if (match === null) return null;
  const keyId = match[1] as string;
  const linkSignatureBytes = decodeBase64Url(match[2] as string);
  if (linkSignatureBytes === null || linkSignatureBytes.length !== RELAY_SIGNATURE_BYTES) {
    return null;
  }
  return { keyId, linkSignatureBytes };
}

/** Whether `value` has the shape of a relay signature (not whether it verifies). */
export function isRelaySignature(value: unknown): value is string {
  return parseRelaySignature(value) !== null;
}

/** Builds the `sig` value from an encoded session key and link signature. */
export function formatRelaySignature(sessionPublicKey: string, linkSignature: string): string {
  return `${relaySessionKeyId(sessionPublicKey)}.${linkSignature}`;
}

/** One certificate as it appears in {@link RelayCertDocument}. */
export interface RelayCertJson {
  /** Session public key, base64url (87 chars). */
  readonly pub: string;
  /** notBefore, unix seconds. */
  readonly nb: number;
  /** notAfter, unix seconds. */
  readonly na: number;
  /** Root signature over {@link relayCertMessage}, base64url (86 chars). */
  readonly sig: string;
}

/** Body of `GET {@link RELAY_CERT_PATH}`. */
export interface RelayCertDocument {
  readonly v: typeof RELAY_CERT_DOCUMENT_VERSION;
  readonly certs: readonly RelayCertJson[];
}

/** A certificate whose shape and bounds were checked; nothing is verified. */
export interface RelayCert {
  readonly sessionPublicKey: string;
  readonly sessionPublicKeyBytes: Uint8Array;
  readonly keyId: string;
  readonly notBefore: number;
  /** Greater than `notBefore`, at most {@link RELAY_CERT_MAX_LIFETIME_SECONDS} later. */
  readonly notAfter: number;
  /** Root signature as it appeared in the document (base64url). */
  readonly certSignature: string;
  readonly certSignatureBytes: Uint8Array;
}

function hasExactKeys(value: unknown, keys: readonly string[]): value is Record<string, unknown> {
  if (typeof value !== 'object' || value === null || Array.isArray(value)) return false;
  const own = Object.keys(value);
  return own.length === keys.length && keys.every((key) => own.includes(key));
}

function isSeconds(value: unknown): value is number {
  return (
    typeof value === 'number' && Number.isSafeInteger(value) && value > 0 && value <= MAX_SECONDS
  );
}

function parseCert(value: unknown): RelayCert | null {
  if (!hasExactKeys(value, ['pub', 'nb', 'na', 'sig'])) return null;
  const { pub, nb, na, sig } = value;
  if (typeof pub !== 'string' || !PUBLIC_KEY_RE.test(pub)) return null;
  if (typeof sig !== 'string' || sig.length !== SIGNATURE_CHARS) return null;
  if (!isSeconds(nb) || !isSeconds(na)) return null;
  if (na <= nb || na - nb > RELAY_CERT_MAX_LIFETIME_SECONDS) return null;
  const pubBytes = decodeBase64Url(pub);
  if (pubBytes === null || pubBytes.length !== RELAY_PUBLIC_KEY_BYTES || pubBytes[0] !== 0x04) {
    return null;
  }
  const sigBytes = decodeBase64Url(sig);
  if (sigBytes === null || sigBytes.length !== RELAY_SIGNATURE_BYTES) return null;
  return {
    sessionPublicKey: pub,
    sessionPublicKeyBytes: pubBytes,
    keyId: relaySessionKeyId(pub),
    notBefore: nb,
    notAfter: na,
    certSignature: sig,
    certSignatureBytes: sigBytes,
  };
}

/**
 * Parses the certificate document text, or returns `null` unless it is exactly
 * `{"v":1,"certs":[{"pub","nb","na","sig"}, ...]}` with 1 to
 * {@link RELAY_CERT_DOCUMENT_MAX_CERTS} well-formed certificates and no other
 * keys, within {@link RELAY_CERT_DOCUMENT_MAX_BYTES} characters.
 */
export function parseRelayCertDocument(text: unknown): readonly RelayCert[] | null {
  if (typeof text !== 'string' || text.length > RELAY_CERT_DOCUMENT_MAX_BYTES) return null;
  let value: unknown;
  try {
    value = JSON.parse(text);
  } catch {
    return null;
  }
  if (!hasExactKeys(value, ['v', 'certs'])) return null;
  if (value.v !== RELAY_CERT_DOCUMENT_VERSION) return null;
  const certs = value.certs;
  if (!Array.isArray(certs) || certs.length === 0) return null;
  if (certs.length > RELAY_CERT_DOCUMENT_MAX_CERTS) return null;
  const parsed: RelayCert[] = [];
  for (const cert of certs) {
    const one = parseCert(cert);
    if (one === null) return null;
    parsed.push(one);
  }
  return parsed;
}

/** Whether `value` has the shape of an encoded relay public key. */
export function isRelayPublicKey(value: unknown): value is string {
  return typeof value === 'string' && PUBLIC_KEY_RE.test(value);
}

/**
 * The origin of a relay URL in the form both sides sign and verify
 * (`wss://abc.trycloudflare.com`): scheme and host, lowercased, with an
 * explicit `:443` dropped. `null` when `relayUrl` is not a `wss:` URL, has
 * userinfo, or has no host. Path, query and hash are not part of it.
 *
 * Parsed by hand because this module may not use `URL` (no DOM, no Node).
 */
export function relayOriginOf(relayUrl: string): string | null {
  const match = /^wss:\/\/([^/?#@\s]+)(?:[/?#]|$)/i.exec(relayUrl);
  const authority = match?.[1];
  if (authority === undefined) return null;
  const host = authority.toLowerCase().replace(/:443$/, '');
  if (!/^(?:[a-z0-9._-]+|\[[0-9a-f:]+\])(?::\d{1,5})?$/.test(host)) return null;
  return `wss://${host}`;
}

/**
 * The byte string the root key signs to certify a session key:
 * `ait-relay-cert-v1\n<sessionPub>\n<notBefore>\n<notAfter>`.
 *
 * @param sessionPublicKey - The session public key exactly as it appears in `sig`.
 */
export function relayCertMessage(
  sessionPublicKey: string,
  notBefore: number,
  notAfter: number,
): string {
  return `${RELAY_CERT_DOMAIN}\n${sessionPublicKey}\n${notBefore}\n${notAfter}`;
}

/**
 * The byte string the session key signs for one attach link:
 * `ait-relay-sig-v2\n<relay origin>\n<at code>`.
 *
 * @param relayOrigin - Origin from {@link relayOriginOf}, e.g. `wss://abc.trycloudflare.com`.
 * @param atCode - The `at` code of the same attach link.
 */
export function relayLinkMessage(relayOrigin: string, atCode: string): string {
  return `${RELAY_LINK_DOMAIN}\n${relayOrigin}\n${atCode}`;
}

const BASE64URL_ALPHABET = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_';

/**
 * Decodes unpadded base64url into bytes, or `null` when it is not valid. Only
 * the canonical encoding is accepted: the unused low bits of the last
 * character must be zero, so each byte string has exactly one text form.
 */
export function decodeBase64Url(value: string): Uint8Array | null {
  if (!/^[A-Za-z0-9_-]*$/.test(value) || value.length % 4 === 1) return null;
  const bytes: number[] = [];
  let buffer = 0;
  let bits = 0;
  for (const char of value) {
    buffer = (buffer << 6) | BASE64URL_ALPHABET.indexOf(char);
    bits += 6;
    if (bits >= 8) {
      bits -= 8;
      bytes.push((buffer >> bits) & 0xff);
      buffer &= (1 << bits) - 1;
    }
  }
  if (buffer !== 0) return null;
  return Uint8Array.from(bytes);
}

const HOST_NAME_RE = new RegExp(`^[A-Za-z0-9._-]{1,${RELAY_HOST_NAME_MAX_CHARS}}$`);

/**
 * Reduces a machine name (for example `os.hostname()`) to what a link may
 * carry: ASCII letters, digits, `.`, `-` and `_`, at most
 * {@link RELAY_HOST_NAME_MAX_CHARS} characters, no trailing `.local`. Spaces
 * become `-`, other characters are dropped, and leading or trailing
 * separators are trimmed. `undefined` when nothing is left.
 */
export function sanitizeRelayHostName(raw: unknown): string | undefined {
  if (typeof raw !== 'string') return undefined;
  let name = raw
    .trim()
    .replace(/\s+/g, '-')
    .replace(/[^A-Za-z0-9._-]/g, '');
  // Cut first, then strip, so a cut that lands before `.local` still ends clean.
  name = name.slice(0, RELAY_HOST_NAME_MAX_CHARS);
  for (let i = 0; i < 4; i++) {
    name = name.replace(/\.local$/i, '').replace(/^[._-]+|[._-]+$/g, '');
  }
  return name === '' || /\.local$/i.test(name) ? undefined : name;
}

/** Whether `value` is a name {@link sanitizeRelayHostName} could have produced. */
export function isRelayHostName(value: unknown): value is string {
  return typeof value === 'string' && HOST_NAME_RE.test(value) && !/\.local$/i.test(value);
}

/**
 * Parses an `ahs` value (the session signature over {@link relayHostMessage}),
 * or returns `null` when it is malformed. It carries no key id: it is checked
 * against the certificate that the key id of `sig` picks.
 */
export function parseRelayHostSignature(value: unknown): Uint8Array | null {
  if (typeof value !== 'string' || value.length !== SIGNATURE_CHARS) return null;
  const bytes = decodeBase64Url(value);
  return bytes !== null && bytes.length === RELAY_SIGNATURE_BYTES ? bytes : null;
}

/**
 * The byte string the session key signs for the developer computer's name in
 * one attach link: `ait-relay-host-v1\n<relay origin>\n<at code>\n<name>`.
 * The same session key that signs {@link relayLinkMessage} signs it, so one
 * certificate covers both. Binding the origin and the `at` code ties the name
 * to that link.
 */
export function relayHostMessage(relayOrigin: string, atCode: string, hostName: string): string {
  return `${RELAY_HOST_DOMAIN}\n${relayOrigin}\n${atCode}\n${hostName}`;
}
